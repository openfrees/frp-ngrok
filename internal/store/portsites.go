// PortSite 是本插件托管的一个本机静态站。
type PortSite struct {
	Port       int    `json:"port"`
	Root       string `json:"root"`
	CustomRoot bool   `json:"customRoot"`
	// Running 是上次用户期望的运行状态，面板重启且插件仍开启时按它恢复。
	Running bool `json:"running"`
}

// PortSitesConfig 是本地端口管理插件的完整配置。
type PortSitesConfig struct {
	Enabled bool       `json:"enabled"`
	Sites   []PortSite `json:"sites"`
}

// PortSiteFile 是站点根目录里的一项。
type PortSiteFile struct {
	Name  string `json:"name"`
	Size  int64  `json:"size"`
	IsDir bool   `json:"isDir"`
}

// DefaultPortSiteRoot 返回插件为该端口准备的默认目录。
func DefaultPortSiteRoot(port int) string {
	return paths.PortSiteRoot(port)
}

// IsManagedPortSiteRoot 判断 root 是不是插件自己建的默认目录。
func IsManagedPortSiteRoot(root string, port int) bool {
	got, err := filepath.Abs(filepath.Clean(root))
	if err != nil {
		return false
	}
	want, err := filepath.Abs(DefaultPortSiteRoot(port))
	if err != nil {
		return false
	}
	return got == want
}

// DefaultDeleteFiles 给出删除弹窗「同时删除文件夹」的默认勾选。
func DefaultDeleteFiles(site PortSite) bool {
	return !site.CustomRoot && IsManagedPortSiteRoot(site.Root, site.Port)
}

// LoadPortSites 读取插件配置；文件不存在时返回空配置。
func LoadPortSites() (PortSitesConfig, error) {
	var c PortSitesConfig
	data, err := os.ReadFile(paths.PortSitesConfigFile())
	if os.IsNotExist(err) {
		return c, nil
	}
	if err != nil {
		return c, err
	}
	if len(data) == 0 {
		return c, nil
	}
	if err := json.Unmarshal(data, &c); err != nil {
		return c, fmt.Errorf("解析端口站点配置失败: %w", err)
	}
	return c, nil
}

// SavePortSites 写入插件配置。
func SavePortSites(c PortSitesConfig) error {
	if err := os.MkdirAll(paths.PortSitesDir(), 0o755); err != nil {
		return err
	}
	if c.Sites == nil {
		c.Sites = []PortSite{}
	}
	data, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return err
	}
	return writeFileAtomic(paths.PortSitesConfigFile(), append(data, '\n'), 0o600)
}

// FindPortSite 按端口查找站点。
func FindPortSite(port int) (PortSite, bool, error) {
	cfg, err := LoadPortSites()
	if err != nil {
		return PortSite{}, false, err
	}
	for _, s := range cfg.Sites {
		if s.Port == port {
			return s, true, nil
		}
	}
	return PortSite{}, false, nil
}

// CreatePortSite 登记一个站点。空 customRoot 时建默认目录并写入占位页。
func CreatePortSite(port int, customRoot string) (PortSite, error) {
	if err := CheckPortConflict(port, nil); err != nil {
		return PortSite{}, err
	}

	site := PortSite{Port: port}
	customRoot = strings.TrimSpace(customRoot)
	if customRoot == "" {
		root := DefaultPortSiteRoot(port)
		if err := os.MkdirAll(root, 0o755); err != nil {
			return PortSite{}, fmt.Errorf("创建站点目录失败: %w", err)
		}
		if err := writeDefaultIndex(root, port); err != nil {
			return PortSite{}, err
		}
		abs, err := filepath.Abs(root)
		if err != nil {
			return PortSite{}, err
		}
		site.Root = abs
		site.CustomRoot = false
	} else {
		abs, err := filepath.Abs(filepath.Clean(customRoot))
		if err != nil {
			return PortSite{}, fmt.Errorf("站点目录不合法: %w", err)
		}
		fi, err := os.Stat(abs)
		if err != nil {
			return PortSite{}, fmt.Errorf("自定义目录不存在或无法访问: %w", err)
		}
		if !fi.IsDir() {
			return PortSite{}, fmt.Errorf("自定义路径必须是文件夹")
		}
		site.Root = abs
		site.CustomRoot = true
	}

	cfg, err := LoadPortSites()
	if err != nil {
		return PortSite{}, err
	}
	cfg.Sites = append(cfg.Sites, site)
	if err := SavePortSites(cfg); err != nil {
		return PortSite{}, err
	}
	return site, nil
}

func writeDefaultIndex(root string, port int) error {
	path := filepath.Join(root, "index.html")
	if existing, err := os.ReadFile(path); err == nil && !isGeneratedPlaceholder(string(existing)) {
		return nil
	}
	return os.WriteFile(path, []byte(renderDefaultIndex(port, Locale())), 0o644)
}

func isGeneratedPlaceholder(html string) bool {
	return strings.Contains(html, "frp-ngrok:portsite-placeholder") ||
		strings.Contains(html, "这是本地端口管理插件自动生成的占位页") ||
		strings.Contains(html, "This placeholder was generated by the local port manager")
}

