// SetPortSiteRunning 记下用户期望的运行状态，供重启后恢复。
func SetPortSiteRunning(port int, running bool) error {
	cfg, err := LoadPortSites()
	if err != nil {
		return err
	}
	found := false
	for i := range cfg.Sites {
		if cfg.Sites[i].Port == port {
			cfg.Sites[i].Running = running
			found = true
			break
		}
	}
	if !found {
		return fmt.Errorf("没有端口 %d 的站点", port)
	}
	return SavePortSites(cfg)
}

// DeletePortSite 从列表移除站点；deleteFiles 为真时只删该站点根目录。
func DeletePortSite(port int, deleteFiles bool) error {
	cfg, err := LoadPortSites()
	if err != nil {
		return err
	}
	var site PortSite
	next := cfg.Sites[:0]
	found := false
	for _, s := range cfg.Sites {
		if s.Port == port {
			site = s
			found = true
			continue
		}
		next = append(next, s)
	}
	if !found {
		return fmt.Errorf("没有端口 %d 的站点", port)
	}
	cfg.Sites = next
	if err := SavePortSites(cfg); err != nil {
		return err
	}
	if !deleteFiles {
		return nil
	}
	return removeSiteRoot(site)
}

func removeSiteRoot(site PortSite) error {
	abs, err := filepath.Abs(filepath.Clean(site.Root))
	if err != nil {
		return fmt.Errorf("站点目录不合法: %w", err)
	}
	if dangerousDeleteRoot(abs) {
		return fmt.Errorf("拒绝删除这个目录：范围太大")
	}
	if !site.CustomRoot {
		want, err := filepath.Abs(DefaultPortSiteRoot(site.Port))
		if err != nil {
			return err
		}
		if abs != want {
			return fmt.Errorf("默认站点目录不匹配，拒绝删除")
		}
	}
	if err := os.RemoveAll(abs); err != nil {
		return fmt.Errorf("删除站点目录失败: %w", err)
	}
	return nil
}

func dangerousDeleteRoot(abs string) bool {
	abs = filepath.Clean(abs)
	if abs == "/" || abs == filepath.VolumeName(abs)+string(filepath.Separator) {
		return true
	}
	home, err := os.UserHomeDir()
	if err == nil && abs == filepath.Clean(home) {
		return true
	}
	for _, p := range []string{paths.AppDir(), paths.PluginsDir(), paths.DataDir(), paths.PortSitesDir()} {
		if abs == filepath.Clean(p) {
			return true
		}
	}
	return false
}

// CheckPortConflict 在创建或启动前检查端口是否可被本插件占用。
func CheckPortConflict(port int, extraReserved []int) error {
	return checkPortConflict(port, extraReserved, 0)
}

// CheckPortConflictExcept 启动已有站点时跳过「自己占用自己」。
func CheckPortConflictExcept(port int, extraReserved []int, exceptPort int) error {
	return checkPortConflict(port, extraReserved, exceptPort)
}

func checkPortConflict(port int, extraReserved []int, exceptPort int) error {
	if port <= 0 || port > 65535 {
		return fmt.Errorf("端口必须是 1-65535 的数字")
	}
	for _, reserved := range consoleListenPorts(extraReserved) {
		if port == reserved {
			return fmt.Errorf("端口 %d 是面板控制台端口，不能占用", port)
		}
	}
	cfg, err := LoadPortSites()
	if err != nil {
		return err
	}
	for _, s := range cfg.Sites {
		if s.Port == port && s.Port != exceptPort {
			return fmt.Errorf("端口 %d 已被本插件另一站点使用", port)
		}
	}
	if name, ok := tunnelLocalPortOwner(port); ok {
		if name != "" {
			return fmt.Errorf("端口 %d 已被隧道占用", port)
		}
		return fmt.Errorf("端口 %d 已被隧道占用", port)
	}
	if portListenBusy(port) {
		return fmt.Errorf("端口 %d 已被本机其他进程占用", port)
	}
	return nil
}

func consoleListenPorts(extra []int) []int {
	seen := map[int]bool{}
	var out []int
	add := func(p int) {
		if p <= 0 || seen[p] {
			return
		}
		seen[p] = true
		out = append(out, p)
	}
	add(paths.DefaultPort)
	if b, err := os.ReadFile(paths.PortFile()); err == nil {
		if n, err := strconv.Atoi(strings.TrimSpace(string(b))); err == nil {
			add(n)
		}
	}
	for _, p := range extra {
		add(p)
	}
	return out
}

func tunnelLocalPortOwner(port int) (string, bool) {
	for _, p := range LoadAllProfiles() {
		tunnels, err := LoadTunnels(p)
		if err != nil {
			continue
		}
		for _, t := range tunnels {
			if t.LocalPort == port {
				return t.Name, true
			}
		}
	}
	return "", false
}

func portListenBusy(port int) bool {
	ln, err := net.Listen("tcp", fmt.Sprintf("127.0.0.1:%d", port))
	if err != nil {
		return true
	}
	_ = ln.Close()
	return false
}

// SafeJoinSite 把相对路径接到站点根下，拒绝穿越。
func SafeJoinSite(root, name string) (string, error) {
	absRoot, err := filepath.Abs(filepath.Clean(root))
	if err != nil {
		return "", fmt.Errorf("站点目录不合法: %w", err)
	}
	name = strings.TrimSpace(name)
	if name == "" {
		return "", fmt.Errorf("文件名不能为空")
	}
	if filepath.IsAbs(name) {
		return "", fmt.Errorf("路径超出站点目录")
	}
	clean := filepath.Clean(name)
	if clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("路径超出站点目录")
	}
	full := filepath.Join(absRoot, clean)
	rel, err := filepath.Rel(absRoot, full)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("路径超出站点目录")
	}
	return full, nil
}

// NormalizeSiteDir 把查询里的相对目录收成 / 分隔路径。空字符串表示站点根。
func NormalizeSiteDir(rel string) (string, error) {
	rel = strings.TrimSpace(strings.ReplaceAll(rel, "\\", "/"))
	rel = strings.Trim(rel, "/")
	if rel == "" || rel == "." {
		return "", nil
	}
	clean := path.Clean(rel)
	if clean == ".." || strings.HasPrefix(clean, "../") {
		return "", fmt.Errorf("路径超出站点目录")
	}
	return clean, nil
}

// SafeJoinSiteDir 把相对目录接到站点根下。空 dir 就是站点根本身。
func SafeJoinSiteDir(root, rel string) (string, error) {
	dir, err := NormalizeSiteDir(rel)
	if err != nil {
		return "", err
	}
	if dir == "" {
		abs, err := filepath.Abs(filepath.Clean(root))
		if err != nil {
			return "", fmt.Errorf("站点目录不合法: %w", err)
		}
		return abs, nil
	}
	return SafeJoinSite(root, filepath.FromSlash(dir))
}

const portSitePageMax = 200

// PaginatePortSiteFiles 按 offset/limit 切一页。limit<=0 表示从 offset 起到末尾。
func PaginatePortSiteFiles(files []PortSiteFile, offset, limit int) (page []PortSiteFile, total, off, lim int) {
	total = len(files)
	if offset < 0 {
		offset = 0
	}
	if offset > total {
		offset = total
	}
	if limit <= 0 {
		return files[offset:], total, offset, 0
	}
	if limit > portSitePageMax {
		limit = portSitePageMax
	}
	end := offset + limit
	if end > total {
		end = total
	}
	return files[offset:end], total, offset, limit
}

// ListPortSiteFiles 列出站点某个相对目录（不递归）。文件夹排在文件前面。
func ListPortSiteFiles(root, rel string) ([]PortSiteFile, string, error) {
	dir, err := NormalizeSiteDir(rel)
	if err != nil {
		return nil, "", err
	}
	abs, err := SafeJoinSiteDir(root, dir)
	if err != nil {
		return nil, "", err
	}
	fi, err := os.Stat(abs)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, "", fmt.Errorf("文件夹不存在")
		}
		return nil, "", fmt.Errorf("无法访问文件夹: %w", err)
	}
	if !fi.IsDir() {
		return nil, "", fmt.Errorf("不是文件夹")
	}
	entries, err := os.ReadDir(abs)
	if err != nil {
		return nil, "", fmt.Errorf("读取站点目录失败: %w", err)
	}
	out := make([]PortSiteFile, 0, len(entries))
	for _, e := range entries {
		info, err := e.Info()
		if err != nil {
			continue
		}
		out = append(out, PortSiteFile{
			Name:  e.Name(),
			Size:  info.Size(),
			IsDir: e.IsDir(),
		})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].IsDir != out[j].IsDir {
			return out[i].IsDir
		}
		return strings.ToLower(out[i].Name) < strings.ToLower(out[j].Name)
	})
	return out, dir, nil
}

// DeletePortSiteFile 删除站点根下的一个文件。拒绝路径穿越，也不删目录。
func DeletePortSiteFile(root, name string) error {
	full, err := SafeJoinSite(root, name)
	if err != nil {
		return err
	}
	fi, err := os.Stat(full)
	if err != nil {
		if os.IsNotExist(err) {
			return fmt.Errorf("文件不存在")
		}
		return fmt.Errorf("无法访问文件: %w", err)
	}
	if fi.IsDir() {
		return fmt.Errorf("不能删除文件夹，请用「打开文件夹」处理")
	}
	if err := os.Remove(full); err != nil {
		return fmt.Errorf("删除失败: %w", err)
	}
	return nil
}

// WritePortSiteFile 把上传内容写到指定相对目录，文件名只取最后一段。
func WritePortSiteFile(root, dir, filename string, r io.Reader) error {
	base := filepath.Base(strings.ReplaceAll(filename, "\\", "/"))
	if base == "." || base == ".." || base == string(filepath.Separator) {
		return fmt.Errorf("文件名不合法")
	}
	parent, err := SafeJoinSiteDir(root, dir)
	if err != nil {
		return err
	}
	fi, err := os.Stat(parent)
	if err != nil || !fi.IsDir() {
		return fmt.Errorf("目标文件夹不存在")
	}
	rel := base
	if clean, err := NormalizeSiteDir(dir); err == nil && clean != "" {
		rel = path.Join(clean, base)
	}
	full, err := SafeJoinSite(root, filepath.FromSlash(rel))
	if err != nil {
		return err
	}
	data, err := io.ReadAll(io.LimitReader(r, 32<<20))
	if err != nil {
		return fmt.Errorf("读取上传文件失败: %w", err)
	}
	return os.WriteFile(full, data, 0o644)
}

// OpenPortSiteFolder 用系统文件管理器打开站点里的某个相对目录。
func OpenPortSiteFolder(root, dir string) error {
	abs, err := SafeJoinSiteDir(root, dir)
	if err != nil {
		return err
	}
	fi, err := os.Stat(abs)
	if err != nil || !fi.IsDir() {
		return fmt.Errorf("站点目录不存在")
	}
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "darwin":
		cmd = exec.Command("open", abs)
	case "windows":
		cmd = exec.Command("explorer", abs)
	default:
		cmd = exec.Command("xdg-open", abs)
	}
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("无法打开文件夹: %w", err)
	}
	return nil
}
